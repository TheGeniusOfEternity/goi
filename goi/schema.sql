CREATE TABLE IF NOT EXISTS nodes (
id INTEGER PRIMARY KEY, parent INTEGER, name TEXT NOT NULL, kind TEXT NOT NULL,
mode INTEGER NOT NULL, size INTEGER NOT NULL DEFAULT 0,
mtime_ns INTEGER NOT NULL, revision INTEGER NOT NULL DEFAULT 1,
account INTEGER, repo INTEGER, branch INTEGER,
remote_sha TEXT, tree_sha TEXT, base_path TEXT, data BLOB,
dirty INTEGER NOT NULL DEFAULT 0, deleted INTEGER NOT NULL DEFAULT 0,
loaded INTEGER NOT NULL DEFAULT 0, writable INTEGER NOT NULL DEFAULT 0,
source_id INTEGER, base_mode TEXT);
CREATE UNIQUE INDEX IF NOT EXISTS names ON nodes(parent,name) WHERE deleted=0;
CREATE TABLE IF NOT EXISTS accounts (id INTEGER PRIMARY KEY, login TEXT, token TEXT);
CREATE TABLE IF NOT EXISTS repos (id INTEGER PRIMARY KEY, account INTEGER,
owner TEXT, name TEXT, active INTEGER DEFAULT 0);
CREATE TABLE IF NOT EXISTS branches (id INTEGER PRIMARY KEY, repo INTEGER,
name TEXT, head TEXT, tree_sha TEXT);
CREATE TABLE IF NOT EXISTS devices (id TEXT PRIMARY KEY, code TEXT, expires REAL,
interval INTEGER, next_poll REAL);
CREATE TABLE IF NOT EXISTS conflicts (node INTEGER PRIMARY KEY, branch INTEGER,
path TEXT, theirs BLOB, remote_sha TEXT, remote_head TEXT, mirror INTEGER, remote_mode TEXT);
CREATE TABLE IF NOT EXISTS publications (branch INTEGER PRIMARY KEY,
base TEXT NOT NULL, target TEXT, payload TEXT NOT NULL, state TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS cache_access (node INTEGER PRIMARY KEY, used_ns INTEGER NOT NULL);
